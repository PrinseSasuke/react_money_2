"""Summarise predictions per control run, without claiming intent is observable."""
import json
from pathlib import Path
import pandas as pd

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'ml'/'paired_flood_results'
SOURCE=ROOT/'evidence'/'paired-flood'


def main():
    p=pd.read_csv(OUT/'predictions.csv.gz');windows=pd.read_csv(OUT/'windows.csv')
    config=json.loads((OUT/'config.json').read_text(encoding='utf8'))
    raw=[json.loads(path.read_text(encoding='utf8')) for path in sorted(SOURCE.glob('ids-control-*.json'))]
    if len(raw)!=4:raise ValueError('Four finished runs required')
    lines=['# Парный контроль: одинаковые запросы при разных назначенных сценариях','',
      'В каждом из четырёх пятиминутных прогонов один источник выполнял одинаковый HTTP GET '
      'на `/api/auth/me` с номинальной частотой 150 запросов/с. По два прогона заранее назначены '
      'как «наплыв» и как «имитация флуда», в порядке A–B–B–A. Код нагрузки, endpoint и тестовый '
      'пользователь совпадали; SHA-256 сценария нагрузки во всех четырёх прогонах одинаков.', '',
      '**Назначенная метка выражает только замысел эксперимента.** Прогоны не подтверждают реальную '
      'атаку, намерение пользователя или отказ в обслуживании. Если запросы одинаковы, '
      'по одним агрегированным метрикам намерение не наблюдается; это отрицательный контроль, '
      'а не оценка обнаружения настоящего DDoS. Учетные данные, метка и ID прогона не подаются в модель.', '',
      'Модели обучаются на исторических train-прогонах и настраиваются на независимых исторических '
      'validation-прогонах; новые четыре прогона используются только как тест. Для каждого из пяти '
      'групповых разбиений и трёх seed считаются шесть перекрывающихся окон на прогон с одинаковой '
      '180-секундной историей и 60-секундным запасом `rate()`. Исторические данные имеют ограничения '
      'временных меток и подтверждения инъекций. Показаны доли предсказаний «атака» внутри каждого '
      'прогона; повторные окна и модели не являются независимыми экспериментами.', '',
      '| Назначенный сценарий | Прогон | RPS в окнах: min–max | RF | MLP | Transformer |',
      '|---|---|---:|---:|---:|---:|']
    for r in sorted(raw,key=lambda x:x['created_at_epoch']):
        sub=p[p.run_id==r['run_id']];w=windows[windows.run_id==r['run_id']]
        vals=[(sub[sub.model==m].prediction=='attack').mean() for m in ('rf','mlp','transformer')]
        lines.append(f"| {r['assigned_condition']} | {r['run_id']} | "
            f"{w.observed_rps.min():.1f}–{w.observed_rps.max():.1f} | "+
            ' | '.join(f'{v:.3f}' for v in vals)+' |')
    lines += ['', 'Между прогонами записывались моментальные проверки RPS, 5xx, готовности backend, '
      'БД, экспортеров и числа реплик; следующий прогон начинался после наблюдения двух готовых реплик '
      'и двух реплик HPA. Это не доказывает полное восстановление состояния приложения. '
      'На класс приходится только два прогона, выполненных в одном окружении одним источником; '
      'результаты не оценивают эксплуатационную частоту ложных тревог или пропусков.', '',
      'Исходные результаты запросов Prometheus и статусы Job, журнал ожидания, контрольные суммы '
      'и список воспроизведения сохранены отдельно. Это результаты PromQL, а не полный архив сырых '
      'счётчиков; возможная подстановка нулей при отсутствии ряда требует отдельной интерпретации.', '',
      f"SHA-256 сценария: `{config['script_hash']}`. Пооконные ответы и составы обучения: `paired_flood_results/`. "]
    (ROOT/'ml'/'PAIRED_FLOOD_RESULTS.md').write_text('\n'.join(lines)+'\n',encoding='utf8')
    print('\n'.join(lines))


if __name__=='__main__':main()
